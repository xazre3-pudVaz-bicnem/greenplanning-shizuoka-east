  slug: string;
  /** 市町名（見出し・title に使う） */
  name: string;
  region: RegionKey;
  /** 沼津の店舗からの距離感（文章で）。数値の断定は避ける */
  access: string;
  /** その地域について書けること（地形・気候・住宅事情など、一般に知られている事実） */
  intro: string[];
  /** 地域の庭で起きやすいこと → 人工芝での考え方 */
