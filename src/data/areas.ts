export function getArea(slug: string) {
  return areaPages.find((a) => a.slug === slug);
}

export function regionLabel(key: RegionKey) {
  return regions.find((r) => r.key === key)?.label ?? '';
}

/** 市町名からエリアページを引く（伊豆の各市町は「伊豆地域」ページへ） */
export function areaPageForMunicipality(name: string): AreaPage | undefined {
  const direct = areaPages.find((a) => a.name === name);
  if (direct) return direct;
  if (regions.find((r) => r.key === 'izu')?.municipalities.includes(name)) return getArea('izu');
  return undefined;
}
